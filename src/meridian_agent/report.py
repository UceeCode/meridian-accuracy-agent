"""Writes outputs/: report.md (humans), findings.json (machines), attribution_table.csv (one row per flagged task), audit_log.jsonl."""
from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

from . import config as C

CAT_ORDER = ["EMPLOYEE", "SYSTEM", "PROCEDURE", "SHARED", "UNDETERMINED"]
SCEN_LABEL = {"S0_as_flagged": "S0 As flagged (management's basis)", "S1_minus_high_confidence_nonemployee": "S1 Minus HIGH-confidence system/procedure",
              "S2_minus_all_system_and_procedure": "S2 Minus ALL system/procedure", "S3_person_involved_medium_plus_only": "S3 Person-involved, medium+ evidence only"}


def _pct(x): return f"{x:.1%}"


def _table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _template_summary(res) -> str:
    s, f = res["summary"], res["rates"]["firm"]
    c = s["new_category_counts"]
    return (f"{s['total_flagged']} of 400 tasks (19.0%) were flagged in September. The old evaluation system charged {s['old_system_counts'].get('EMPLOYEE', 0)} of them to employees "
            f"mostly by default. Re-examined against the records, {c.get('EMPLOYEE', 0)} point to an employee-side cause (only some with real evidence), "
            f"{c.get('SYSTEM', 0)} to automated systems, {c.get('PROCEDURE', 0)} to a management-approved procedure, {c.get('SHARED', 0)} to a mix, and "
            f"{c.get('UNDETERMINED', 0)} cannot be attributed. Whether the firm is above the 15% threshold depends on that attribution: "
            f"{_pct(f['S0_as_flagged']['rate'])} as flagged, {_pct(f['S2_minus_all_system_and_procedure']['rate'])} after removing system and procedure causes. "
            "The agent makes no recommendation on a salary deduction.")


def build_markdown(res: dict) -> str:
    V = res["verdicts"]
    s, rates, depts = res["summary"], res["rates"], res["dept_category_matrix"]
    L = []
    w = L.append
    w("# Meridian & Co. - September 2026 Accuracy Assessment")
    w(f"*Generated by the Accuracy Monitoring Agent ({res['mode']}{', model ' + res['model'] if res.get('model') else ''}) on {res['generated_at']}. "
      "Decision support only. This report makes **no recommendation on any salary deduction** and does not find any individual negligent.*\n")

    w("## 1. Bottom line")
    nar = res.get("model_narrative")
    if nar and nar.get("executive_summary"):
        w(nar["executive_summary"] + "\n")
        w("*(Summary written by the model and passed through the output safeguards. Figures below are computed by code.)*\n")
    else:
        w(_template_summary(res) + "\n")
    if nar and nar.get("key_findings"):
        w("**Model's key findings:**")
        for k in nar["key_findings"]: w(f"- {k}")
        w("")
    if nar and nar.get("open_questions"):
        w("**Open questions the model raised:**")
        for k in nar["open_questions"]: w(f"- {k}")
        w("")

    w("## 2. Who or what the errors came from: old system vs. evidence-based")
    c = s["new_category_counts"]
    old = s["old_system_counts"]
    w(f"The old system attributed **{old.get('EMPLOYEE', 0)} errors to employees and {old.get('SYSTEM', 0)} to SYSTEM**; "
      f"{sum(1 for v in V if v['old_attribution'] != 'SYSTEM')} of its attributions were 'assigned employee (default)'.\n")
    w(_table(["Category", "Count", "of which high", "medium", "low"],
             [[k, c.get(k, 0)] + [s["new_category_confidence_counts"].get(f"{k}/{lv}", 0) for lv in ("high", "medium", "low")] for k in CAT_ORDER]))
    w("\n**By department:**\n")
    w(_table(["Department", "Flagged"] + CAT_ORDER, [[d, sum(m.values())] + [m.get(k, 0) for k in CAT_ORDER] for d, m in sorted(depts.items())]))
    w("\n*EMPLOYEE at 'low' confidence means: a typically human-type error with no external cause found, attributed by elimination only. "
      "It is not evidence of carelessness.*\n")

    w("## 3. Error rate under different attribution assumptions")
    w("Policy threshold: 15%. The result changes depending on who is blamed.\n")
    scopes = ["firm"] + sorted(k for k in rates if k != "firm")
    rows = []
    for sc in SCEN_LABEL:
        rows.append([SCEN_LABEL[sc]] + [f"{_pct(rates[x][sc]['rate'])} ({rates[x][sc]['errors']}) {'ABOVE' if rates[x][sc]['above_15pct_threshold'] else 'below'}" for x in scopes])
    w(_table(["Scenario"] + [("Firm" if x == "firm" else x) for x in scopes], rows))
    w(f"\nUndetermined errors (could land either way): {s['new_category_counts'].get('UNDETERMINED', 0)} of {s['total_flagged']} ({s['undetermined_share']:.0%}).\n")

    w("## 4. What is driving the errors")
    imp = res["procedure_impact"].get("PROC-FR-07", {})
    cs = imp.get("currency_split", {})
    if cs:
        mb, ma = cs["multi_currency"]["before_latest_change"], cs["multi_currency"]["after_latest_change"]
        sa = cs["single_currency"]["after_latest_change"]
        n_proc = sum(1 for v in V if v["category"] == "PROCEDURE")
        w(f"**4.1 A procedure change (largest single finding).** PROC-FR-07 v3 took effect {cs['split_date']} (approved by the CFO; note says *'staff briefing deferred'*). "
          f"Multi-currency consolidation tasks: {mb['flagged']}/{mb['tasks']} flagged before, **{ma['flagged']}/{ma['tasks']} after**. Single-currency tasks after: {sa['flagged']}/{sa['tasks']}. "
          f"{n_proc} flagged tasks were applied exactly as published, with a signed checklist. On v3.1 (29 Sep, clarified) 0 of 5 were flagged. Small numbers; a strong association, not proof. "
          f"Evidence: proc:PROC-FR-07@v3, proc:PROC-FR-07@v3.1.\n")
    fx = [v for v in V if v["rule"] == "R1_STALE_FX_CACHE"]
    w(f"**4.2 FX feed failure, 17 Sep.** FX-Rate-Sync failed at 02:00; the ledger posted on cached 16 Sep rates. {len(fx)} flagged tasks are attributed to SYSTEM at high confidence "
      "(the old system caught these four). IT's notice says 'no downstream impact'; the log shows 7 postings on the stale rate, and the manual load covered only USD and EUR. Evidence: log:LG-0023.\n")
    ov = [v for v in V if v["rule"] == "R2_SERVICE_ACCOUNT_OVERRIDE"]
    mism = [v for v in V if v["performed_by"] and v["performed_by"] != v["assigned_employee"]]
    w(f"**4.3 Service-account overrides and mis-attribution.** SVC-POSTING manually overrode the posted amount on {len(ov)} transactions; all {len(ov)} were flagged. "
      f"In {len(mism)} flagged tasks someone other than the assigned employee did the work, yet the old system blamed the assignee. Who triggers these overrides is not recorded.\n")
    fb = [v for v in V if v["rule"].startswith("R4")]
    w(f"**4.4 Auto-coding fallbacks.** The Auto-Coding-Engine logged 10 'tax-code mapping fallback' warnings (22-24 Sep, 28 Sep); {len(fb)} of these tasks were flagged as wrong account code. The old system ignores WARNINGs.\n")
    emp_m = [v for v in V if v["category"] == "EMPLOYEE" and v["confidence"] in ("medium", "high")]
    ru = Counter(v["rule"] for v in emp_m)
    er = res["employee_review"]
    w(f"**4.5 Real employee-side signals (the evidence cuts both ways).** {len(emp_m)} errors have medium-or-higher evidence of an employee-side cause: "
      f"{ru.get('R7_CHECKLIST_UNSIGNED', 0)} where the checklist was not signed and {ru.get('R5_WARNING_OVERRIDDEN', 0)} where a person overrode a Duplicate-Detector warning. "
      f"Unsigned checklists are {_pct(er['unsigned_rate_among_flagged_tasks'])} of flagged tasks vs {_pct(er['firm_unsigned_checklist_rate'])} of all tasks, so process discipline is a genuine, separate issue worth management's attention.\n")
    w("**4.6 Evidence gaps.** 6 flagged transactions have no task record. The Log-Collector captured nothing on 8-9 Sep (disk quota). Errors in those windows cannot be cleared or blamed.\n")

    w("## 5. Claims in the documents, tested against the records")
    w(_table(["ID", "Source", "Claim", "Status", "Detail"], [[x["id"], x["source"].replace(".md", ""), x["claim"], f"**{x['status']}**", x["detail"]] for x in res["claims"]]))
    w("")

    w("## 6. Escalations (humans must resolve before any person-level use)")
    for e in res["escalations"]:
        w(f"- **[{e['severity']}] {e['title']}** ({e['id']}) - {e['detail']}  \n  *Evidence:* {', '.join(e['evidence'][:6]) or 'n/a'}")
    w(f"\n*Route to:* {res['escalations'][0]['route_to'] if res['escalations'] else 'n/a'}\n")

    w("## 7. Patterns for human review (NOT findings of negligence)")
    w(f"Listed only if an employee has at least {er['minimum_errors_for_listing']} errors with medium-or-higher evidence of an employee-side cause. "
      "Numbers are small and several drivers are not under the employee's control. A person appearing here means: *look at the task evidence together with them*.\n")
    rows = [[p["employee_id"], p["name"], p["role"], p["tasks_performed_per_task_records"], p["flagged_tasks_they_performed"],
             p["old_system_blamed_them_for"], p["old_blamed_but_not_responsible_now"], p["medium_plus_employee_side_errors"],
             _pct(p["unsigned_checklist_rate"]), _pct(p["undetermined_share_of_their_flagged"])] for p in er["review_candidates"]]
    w(_table(["ID", "Name", "Role", "Tasks done", "Flagged", "Old system blamed", "Of those, not theirs now", "Medium+ employee-side", "Unsigned checklists", "Their flagged that are undetermined"], rows) if rows else "*No employee meets the listing criteria.*")
    w("\nAll employees (context): ")
    w(_table(["ID", "Dept", "Tasks", "Flagged", "Old blamed", "Not theirs now", "Medium+ emp-side", "Unsigned"],
             [[p["employee_id"], p["department"], p["tasks_performed_per_task_records"], p["flagged_tasks_they_performed"], p["old_system_blamed_them_for"],
               p["old_blamed_but_not_responsible_now"], p["medium_plus_employee_side_errors"], _pct(p["unsigned_checklist_rate"])] for p in er["profiles"]]))
    w("")

    w("## 8. The salary deduction")
    db = res["deduction_briefing"]
    w(db["agent_position"] + "\n")
    w("Preconditions that would have to hold before management could even consider a proposal:\n")
    w(_table(["Condition", "Met?", "Why"], [[p["condition"], "yes" if p["met"] else "**NO**", p["why"]] for p in db["preconditions_before_management_could_consider_it"]]))
    w(f"\n{db['note']}\n")

    w("## 9. Safeguard activity and how to check this report")
    if res["safeguard_events"]:
        for e in res["safeguard_events"]: w(f"- {e['type']}: {json.dumps({k: v for k, v in e.items() if k != 'type'})[:240]}")
    else:
        w("- No safeguard blocks fired in this run.")
    w("- Every tool call is in `audit_log.jsonl`. Every verdict in `attribution_table.csv` lists its evidence ids; each id points to a row in the source data.")
    w("- This agent has read-only access to the data. It cannot change financial records, employee records or the evaluation system's output.")
    return "\n".join(L)


def write_outputs(res: dict, audit: list, out_dir) -> None:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.md").write_text(build_markdown(res), encoding="utf-8")
    (out / "findings.json").write_text(json.dumps(res, indent=2, default=str), encoding="utf-8")
    with open(out / "attribution_table.csv", "w", newline="", encoding="utf-8") as f:
        cols = ["txn_id", "department", "error_category", "assigned_employee", "performed_by", "old_attribution", "category", "confidence",
                "responsible_employee", "rule", "reasoning", "evidence", "caveats", "reviewed_by_model"]
        wr = csv.DictWriter(f, fieldnames=cols)
        wr.writeheader()
        for v in res["verdicts"]:
            wr.writerow({**{k: v[k] for k in cols}, "evidence": ";".join(v["evidence"]), "caveats": " | ".join(v["caveats"])})
    with open(out / "audit_log.jsonl", "w", encoding="utf-8") as f:
        for a in audit:
            f.write(json.dumps(a, default=str) + "\n")
